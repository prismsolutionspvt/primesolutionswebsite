/**
 * Generates supabase/seed.sql from the approved starter content in src/content (the company portfolio wording).
 * Run:  npm run db:seed:generate
 *
 * The seed is idempotent: every table is filled only when it is EMPTY, so re-running it never overwrites
 * edits the owner made in the admin panel. The last statement flips site_settings.content_seeded, which tells the
 * public website that the database (not the built-in defaults) is now the source of truth.
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

// ── tiny TypeScript loader (no type-checking, `import type` is erased) ──
const cache = new Map();
function load(file) {
  if (!path.extname(file)) file += ".ts";
  if (cache.has(file)) return cache.get(file).exports;
  const out = ts.transpileModule(fs.readFileSync(file, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const mod = { exports: {} };
  cache.set(file, mod);
  const req = (p) => (p.startsWith(".") ? load(path.resolve(path.dirname(file), p)) : require(p));
  new Function("require", "module", "exports", out)(req, mod, mod.exports);
  return mod.exports;
}

const C = load(path.join(root, "src/content/index.ts"));
const cfg = load(path.join(root, "src/config/site.ts"));

// ── SQL literal helpers ──
const q = (s) => `'${String(s ?? "").replace(/'/g, "''")}'`;
const arr = (a) => (a && a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);
const js = (o) => `${q(JSON.stringify(o))}::jsonb`;
const groupLabel = (id) => C.serviceGroups.find((g) => g.id === id)?.label ?? "";
const faqLabel = (id) => C.faqCategories.find((c) => c.id === id)?.label ?? "General";

const out = [];
const push = (s) => out.push(s);
/** Fill a table only when it is empty (never overwrite owner edits). */
const fillIfEmpty = (table, body) => push(`do $$ begin\n  if not exists (select 1 from public.${table}) then\n${body}\n  end if;\nend $$;\n`);

push(`-- ════════════════════════════════════════════════════════════════════════════
-- STARTER CONTENT — generated by scripts/generate-seed.mjs from src/content (the Prism Solutions portfolio).
-- Do not edit by hand: change src/content and run  npm run db:seed:generate.
-- Idempotent: tables that already contain rows are left untouched.
-- No testimonials, reviews, client names, statistics or team identities are seeded — by design.
-- ════════════════════════════════════════════════════════════════════════════
`);

// ── section copy ──
const sec = (key, { eyebrow = "", heading = "", intro = "", body = [], extra = {} }) =>
  `  (${q(key)}, ${q(eyebrow)}, ${q(heading)}, ${q(intro)}, ${arr(body)}, ${js(extra)})`;
push(`insert into public.site_sections (key, eyebrow, heading, intro, body, extra) values
${[
  sec("hero", { eyebrow: C.hero.eyebrow, heading: C.hero.headline, intro: C.hero.text, extra: { primaryCta: C.hero.primaryCta, secondaryCta: C.hero.secondaryCta, accent: C.hero.accent } }),
  sec("about", { eyebrow: C.about.eyebrow, heading: C.about.heading, body: C.about.overview, extra: { principlesLine: C.about.principlesLine, pillars: C.positioning } }),
  sec("values", { eyebrow: C.valuesIntro.eyebrow, heading: C.valuesIntro.heading }),
  sec("services", { eyebrow: C.servicesIntro.eyebrow, heading: C.servicesIntro.heading, intro: C.servicesIntro.text }),
  sec("why", { eyebrow: C.why.eyebrow, heading: C.why.heading }),
  sec("industries", { eyebrow: C.industriesIntro.eyebrow, heading: C.industriesIntro.heading, intro: C.industriesIntro.text, extra: { disclaimer: C.industriesIntro.disclaimer } }),
  sec("approach", { eyebrow: C.approach.eyebrow, heading: C.approach.heading, intro: C.approach.text }),
  sec("team", { eyebrow: C.teamIntro.eyebrow, heading: C.teamIntro.heading, intro: C.teamIntro.text }),
  sec("reviews", {
    eyebrow: "Reviews",
    heading: "Leave a review.",
    intro: "Share your experience with Prism Solutions. Every review is read by our team and appears here once it has been approved.",
  }),
  sec("faq", { eyebrow: C.faqIntro.eyebrow, heading: C.faqIntro.heading, intro: C.faqIntro.text }),
  sec("contact", { eyebrow: C.cta.eyebrow, heading: C.cta.heading, intro: C.cta.text, extra: { button: C.cta.button, fineprint: C.cta.fineprint } }),
  sec("commitment", { eyebrow: C.commitment.eyebrow, heading: C.commitment.heading, intro: C.commitment.text, extra: { items: C.commitment.items } }),
].join(",\n")}
on conflict (key) do nothing;
`);

// ── mission & vision (singleton row already exists) ──
const d = C.direction;
push(`update public.mission_vision set
  mission_label = ${q(d.mission.label)}, mission_text = ${q(d.mission.text)}, mission_highlights = ${arr(d.mission.highlights)},
  vision_label = ${q(d.vision.label)}, vision_text = ${q(d.vision.text)}, vision_highlights = ${arr(d.vision.highlights)}
where id = 1 and mission_text = '' and vision_text = '';
`);

// ── services + subcategories ──
fillIfEmpty(
  "services",
  `    insert into public.services (slug, name, ray_label, group_label, tagline, summary, note, sort_order) values
${C.services
  .map((s, i) => `      (${q(s.id)}, ${q(s.name)}, ${q(s.ray)}, ${q(groupLabel(s.group))}, ${q(s.tagline)}, ${q(s.summary)}, ${q(s.note ?? "")}, ${(i + 1) * 10})`)
  .join(",\n")};
    insert into public.service_subcategories (service_id, title, detail, sort_order)
    select s.id, v.title, v.detail, v.ord from public.services s join (values
${C.services.flatMap((s) => s.items.map((it, j) => `      (${q(s.id)}, ${q(it.title)}, ${q(it.detail ?? "")}, ${(j + 1) * 10})`)).join(",\n")}
    ) as v(slug, title, detail, ord) on v.slug = s.slug;`,
);

fillIfEmpty(
  "industries",
  `    insert into public.industries (slug, name, summary, note, fits, scene, sort_order) values
${C.industries.map((x, i) => `      (${q(x.id)}, ${q(x.name)}, ${q(x.summary)}, ${q(x.note ?? "")}, ${arr(x.fits)}, ${q(x.scene)}, ${(i + 1) * 10})`).join(",\n")};`,
);

fillIfEmpty(
  "team_members",
  `    insert into public.team_members (name, designation, bio, sort_order) values
${C.team.map((m, i) => `      (${q(m.name)}, ${q(m.designation)}, ${q(m.description)}, ${(i + 1) * 10})`).join(",\n")};`,
);

const principles = new Set(C.hero.principles.map((p) => p.toLowerCase()));
fillIfEmpty(
  "core_values",
  `    insert into public.core_values (word, line, is_principle, sort_order) values
${C.values.map((v, i) => `      (${q(v.word)}, ${q(v.line)}, ${principles.has(v.word.toLowerCase())}, ${(i + 1) * 10})`).join(",\n")};`,
);

fillIfEmpty(
  "why_prism_items",
  `    insert into public.why_prism_items (title, text, sort_order) values
${C.why.items.map((v, i) => `      (${q(v.title)}, ${q(v.text)}, ${(i + 1) * 10})`).join(",\n")};`,
);

fillIfEmpty(
  "approach_steps",
  `    insert into public.approach_steps (name, text, sort_order) values
${C.approach.stages.map((v, i) => `      (${q(v.name)}, ${q(v.text)}, ${(i + 1) * 10})`).join(",\n")};`,
);

fillIfEmpty(
  "faqs",
  `    insert into public.faqs (question, answer, category, sort_order) values
${C.faqs.map((f, i) => `      (${q(f.q)}, ${q(f.a)}, ${q(faqLabel(f.category))}, ${(i + 1) * 10})`).join(",\n")};`,
);

// ── settings: footer copy and descriptions (contact details intentionally untouched) ──
push(`update public.site_settings set
  seo_description = ${q(cfg.settings.company.description)},
  footer_note = ${q(C.footer.note)},
  footer_marquee = ${arr(C.footer.marquee)},
  content_seeded = true
where id = 1;
`);

const target = path.join(root, "supabase", "seed.sql");
fs.writeFileSync(target, out.join("\n"));
console.log(`Wrote ${path.relative(root, target)} (${out.join("\n").length} bytes)`);
